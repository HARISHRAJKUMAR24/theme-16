    }

    function openProductPage(index) {
        currentProduct = productData[index];
        if (!currentProduct) return;

        currentImageIndex = 0;
        currentQty = 1;
        currentSize = '';

        pzTitle.textContent = currentProduct.title;
        pzTag.textContent = currentProduct.tag;
        pzPrice.textContent = '₹' + currentProduct.price.toLocaleString('en-IN');
        pzMrp.textContent = '₹' + currentProduct.mrp.toLocaleString('en-IN');
        pzSave.textContent = 'SAVE ' + currentProduct.save + '%';
        pzDesc.textContent = currentProduct.description;
        pzQtyValue.textContent = '1';

        pzSizes.querySelectorAll('button').forEach(btn => btn.classList.remove('is-selected'));

        pzMainImage.src = currentProduct.images[0];
        renderPzThumbs();

        pzModal.classList.add('is-open');
        pzModal.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden';
    }

    function renderPzThumbs() {
        pzThumbs.innerHTML = '';
        currentProduct.images.forEach((src, i) => {
            const btn = document.createElement('button');
            btn.type = 'button';
            if (i === currentImageIndex) btn.classList.add('is-active');
            const img = document.createElement('img');
            img.src = src;
            img.alt = 'View ' + (i + 1);
            btn.appendChild(img);
            btn.addEventListener('click', () => {
                currentImageIndex = i;
                pzMainImage.src = src;
                pzThumbs.querySelectorAll('button').forEach((b, bi) => {
                    b.classList.toggle('is-active', bi === i);
                });
            });
            pzThumbs.appendChild(btn);
        });
    }

    function closeProductPage() {
        pzModal.classList.remove('is-open');
        pzModal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = '';
    }

    document.querySelectorAll('.product').forEach(card => {
        card.addEventListener('click', event => {
            if (event.target.closest('.size-option')) return;
            const index = parseInt(card.dataset.productIndex, 10);
            launchProduct(card, index);
        });
    });

    document.getElementById('pzClose').addEventListener('click', closeProductPage);
    document.getElementById('pzBackdrop').addEventListener('click', closeProductPage);

    document.addEventListener('keydown', e => {
        if (e.key === 'Escape' && pzModal.classList.contains('is-open')) closeProductPage();
    });

    pzSizes.querySelectorAll('button').forEach(btn => {
        btn.addEventListener('click', () => {
            pzSizes.querySelectorAll('button').forEach(b => b.classList.remove('is-selected'));
            btn.classList.add('is-selected');
            currentSize = btn.dataset.size;
        });
    });

    document.getElementById('pzQtyMinus').addEventListener('click', () => {
        currentQty = Math.max(1, currentQty - 1);
        pzQtyValue.textContent = currentQty;
    });
    document.getElementById('pzQtyPlus').addEventListener('click', () => {
        currentQty++;
        pzQtyValue.textContent = currentQty;
    });

    document.getElementById('pzAddBtn').addEventListener('click', () => {
        if (!currentSize) {
            alert('Please select a size first.');
            return;
        }
        console.log('Added to cart:', {
            product: currentProduct.title,
            size: currentSize,
            quantity: currentQty
        });
        alert('Added to cart!');
        closeProductPage();
    });
</script>